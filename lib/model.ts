// The token radar's model: one sealed snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) plus every
// other rankable pre-token protocol below the floor: the early rows the radar exists to find. A
// protocol is pre-token when its record carries no token (no market cap, no CoinGecko id, no symbol);
// the snapshot's live-token protocols are kept apart and shown with the market's own values, never
// mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, and from a multiple the snapshot
// itself supplies: for each category, the median market-cap-to-TVL ratio of the live-token protocols
// in that category is what the market pays for a dollar of TVL there. Categories with fewer than
// three live comparables fall back to the global median across all live-token protocols. No protocol
// name is ever special-cased: the same function scores every row.
//
//   multiple     = median(mcap_usd / tvl_usd) over live-token protocols in the category
//                  (n >= 3; else the global median), clamped to [0.05, 1.50]
//   base         = tvl_usd x multiple
//   growth       = clamp(change_7d, -60, 120) per cent
//   growthMult   = 1 + (growth / 100) x 0.5
//   maturity     = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   chainMult    = 1 + 0.02 x min(chains - 1, 4)
//   implied      = max(1, round(base x growthMult x maturity x chainMult))
//
// The constants are stated in the dashboard and changeable in the model; the multiples are read off
// the snapshot at run time, so a different snapshot re-prices every category on its own evidence.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
